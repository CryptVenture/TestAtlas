#!/usr/bin/env node
// scripts/generate-automation.js
//
// Plan 14-07 Task 1 — Automation skeleton generator (V2 PRD §7.14, §19).
//
// Reads flows + issues and emits framework-specific test skeletons under
// `_testatlas/tests/generated_automation/<framework>/`.
//
// Supported frameworks (one of, or `--framework all`):
//
//   playwright   — TypeScript Playwright spec with page-object stubs
//   cypress      — JavaScript Cypress spec with cy.* commands
//   api          — .http file (REST Client / Bruno-compatible)
//   cli          — Bash test script with assertions
//   contract     — Pact-shaped consumer-provider stub (JSON)
//   smoke        — minimal markdown smoke checklist
//
// Each emitted file carries explicit fixture + mock-data sections in
// comments. A companion `<file>.meta.json` tracks the test status:
//   generated-but-not-validated → validated → committed → flaky
//
// CLI:
//   node scripts/generate-automation.js [--cwd <dir>]
//       [--playwright | --cypress | --api | --cli | --contract | --smoke | --framework <name>]
//       [--flow <FLOW-id>] [--issue <ISSUE-id>] [--all]
//
// Programmatic:
//   import { generateAutomation } from './generate-automation.js';
//   const r = await generateAutomation({ cwd, framework, flow, issue, all });

import { mkdir, readdir, readFile, stat } from 'node:fs/promises';
import path from 'node:path';
import { atomicWrite } from './lib/atomic-write.js';

export const STATUS_VALUES = Object.freeze([
  'generated-but-not-validated',
  'validated',
  'committed',
  'flaky',
]);
export const FRAMEWORKS = Object.freeze([
  'playwright',
  'cypress',
  'api',
  'cli',
  'contract',
  'smoke',
]);

async function fileExists(p) {
  try {
    await stat(p);
    return true;
  } catch {
    return false;
  }
}

async function readJsonOr(p, fb) {
  try {
    return JSON.parse(await readFile(p, 'utf8'));
  } catch {
    return fb;
  }
}

function slugify(s) {
  return String(s ?? '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 60);
}

async function listFlows(flowsDir) {
  if (!(await fileExists(flowsDir))) return [];
  const entries = await readdir(flowsDir, { withFileTypes: true });
  const flows = [];
  for (const e of entries) {
    if (!e.isFile() || !e.name.endsWith('.json') || !e.name.startsWith('FLOW-')) continue;
    const json = await readJsonOr(path.join(flowsDir, e.name), null);
    if (json && typeof json === 'object' && json.id) flows.push(json);
  }
  return flows;
}

function fileExt(framework) {
  switch (framework) {
    case 'playwright':
      return '.spec.ts';
    case 'cypress':
      return '.cy.js';
    case 'api':
      return '.http';
    case 'cli':
      return '.sh';
    case 'contract':
      return '.contract.json';
    case 'smoke':
      return '.md';
    default:
      return '.txt';
  }
}

function fixtureBlock(_framework, prefix) {
  const lines = [
    `${prefix} -----------------------------------------------------------`,
    `${prefix} Fixtures required:`,
    `${prefix}   - (declare any fixture files this skeleton depends on)`,
    `${prefix}     e.g. _testatlas/fixtures/<flow>/seed.json`,
    `${prefix} Mock data plan:`,
    `${prefix}   - (describe mocked services, response shapes, time anchors)`,
    `${prefix}     e.g. mock /api/login -> 200 with session cookie`,
    `${prefix} -----------------------------------------------------------`,
  ];
  return lines.join('\n');
}

function renderPlaywright(flow) {
  const slug = slugify(flow.id.replace(/^FLOW-/, ''));
  return [
    `// _testatlas/tests/generated_automation/playwright/${slug}.spec.ts`,
    `// Generated by scripts/generate-automation.js — status: generated-but-not-validated.`,
    `// Source flow: ${flow.id} (${flow.name ?? ''}).`,
    fixtureBlock('playwright', '//'),
    ``,
    `import { expect, test } from '@playwright/test';`,
    ``,
    `test.describe('${flow.id} — ${flow.name ?? ''}', () => {`,
    `  test('walks the documented happy path', async ({ page }) => {`,
    `    // TODO: replace with real entry point.`,
    `    await page.goto(${JSON.stringify(flow.entryPoints?.[0] || '/')});`,
    `    // TODO: drive the documented steps.`,
    `    // Documented expectation:`,
    `    //   ${flow.expectedBehavior?.[0] || 'flow completes without error'}`,
    `    await expect(page).toHaveURL(/.*/);`,
    `  });`,
    `});`,
    ``,
  ].join('\n');
}

function renderCypress(flow) {
  const slug = slugify(flow.id.replace(/^FLOW-/, ''));
  return [
    `// _testatlas/tests/generated_automation/cypress/${slug}.cy.js`,
    `// Generated by scripts/generate-automation.js — status: generated-but-not-validated.`,
    `// Source flow: ${flow.id} (${flow.name ?? ''}).`,
    fixtureBlock('cypress', '//'),
    ``,
    `describe('${flow.id} — ${flow.name ?? ''}', () => {`,
    `  it('walks the documented happy path', () => {`,
    `    cy.visit(${JSON.stringify(flow.entryPoints?.[0] || '/')});`,
    `    // TODO: drive documented steps.`,
    `    // Documented expectation:`,
    `    //   ${flow.expectedBehavior?.[0] || 'flow completes without error'}`,
    `    cy.url().should('match', /.*/);`,
    `  });`,
    `});`,
    ``,
  ].join('\n');
}

function renderApi(flow) {
  const slug = slugify(flow.id.replace(/^FLOW-/, ''));
  return [
    `### _testatlas/tests/generated_automation/api/${slug}.http`,
    `### Generated by scripts/generate-automation.js — status: generated-but-not-validated.`,
    `### Source flow: ${flow.id} (${flow.name ?? ''}).`,
    fixtureBlock('api', '###'),
    ``,
    `### Replace the URL + payload with documented entry points.`,
    `GET {{baseUrl}}${flow.entryPoints?.[0] || '/'}`,
    `Accept: application/json`,
    ``,
    `### Expected: ${flow.expectedBehavior?.[0] || '200 OK'}`,
    ``,
  ].join('\n');
}

function renderCli(flow) {
  const slug = slugify(flow.id.replace(/^FLOW-/, ''));
  return [
    `#!/usr/bin/env bash`,
    `# _testatlas/tests/generated_automation/cli/${slug}.sh`,
    `# Generated by scripts/generate-automation.js — status: generated-but-not-validated.`,
    `# Source flow: ${flow.id} (${flow.name ?? ''}).`,
    fixtureBlock('cli', '#'),
    ``,
    `set -eu`,
    ``,
    `# TODO: drive the documented CLI command(s).`,
    `# Documented expectation: ${flow.expectedBehavior?.[0] || 'exit 0'}`,
    `echo "TODO: replace with actual command" >&2`,
    `exit 0`,
    ``,
  ].join('\n');
}

function renderContract(flow) {
  const slug = slugify(flow.id.replace(/^FLOW-/, ''));
  const body = {
    $schema: 'https://example.com/contract-skeleton',
    consumer: { name: 'TODO-consumer' },
    provider: { name: 'TODO-provider' },
    interactions: [
      {
        description: `Generated from ${flow.id}`,
        providerState: 'TODO-state',
        request: { method: 'GET', path: flow.entryPoints?.[0] || '/' },
        response: { status: 200, headers: { 'Content-Type': 'application/json' }, body: {} },
      },
    ],
    metadata: {
      generated_by: 'scripts/generate-automation.js',
      source_flow: flow.id,
      status: 'generated-but-not-validated',
      fixtures: [],
      mock_data: [
        'Replace the response body with the canonical fixture; mock the provider state with a seeded fixture file under _testatlas/fixtures/.',
      ],
    },
  };
  // Header comment is not valid JSON, so embed a human note inside metadata
  // (above) and emit pretty JSON.
  return [
    `${JSON.stringify(body, null, 2)}\n`,
    `// _testatlas/tests/generated_automation/contract/${slug}.contract.json`,
    `// (Trailing comment block describing fixture + mock data plan)`,
    fixtureBlock('contract', '//'),
    ``,
  ].join('\n');
}

function renderSmoke(flow) {
  return [
    `# Smoke checklist: ${flow.id}`,
    ``,
    `> Generated by scripts/generate-automation.js — status: generated-but-not-validated.`,
    ``,
    `## Source Flow`,
    ``,
    `- ${flow.id} — ${flow.name ?? ''}`,
    ``,
    `## Smoke checks`,
    ``,
    `- [ ] Entry point reachable: \`${flow.entryPoints?.[0] || '/'}\``,
    `- [ ] No console errors`,
    `- [ ] Documented expectation observed: ${flow.expectedBehavior?.[0] || 'happy path completes'}`,
    ``,
    fixtureBlock('smoke', '<!--'),
    ``,
  ].join('\n');
}

const RENDERERS = {
  playwright: renderPlaywright,
  cypress: renderCypress,
  api: renderApi,
  cli: renderCli,
  contract: renderContract,
  smoke: renderSmoke,
};

function makeMeta(flow, framework, relTestPath) {
  return {
    schema_version: '1.0.0',
    generated_by: 'scripts/generate-automation.js',
    framework,
    source_flow: flow.id,
    test_path: relTestPath,
    status: 'generated-but-not-validated',
    status_history: [{ status: 'generated-but-not-validated', at: new Date().toISOString() }],
    fixtures: [],
    mock_data: [],
  };
}

/**
 * @param {{ cwd?: string, framework?: string, flow?: string, issue?: string, all?: boolean }} args
 */
export async function generateAutomation(args = {}) {
  const cwd = args.cwd ?? process.cwd();
  const framework = args.framework;
  if (!framework || !FRAMEWORKS.includes(framework)) {
    const list = FRAMEWORKS.join(', ');
    const err = new Error(`generate-automation: unknown framework "${framework}". Valid: ${list}.`);
    err.code = 'UNKNOWN_FRAMEWORK';
    throw err;
  }

  const flowsDir = path.join(cwd, '_testatlas', 'flows');
  const outDir = path.join(cwd, '_testatlas', 'tests', 'generated_automation', framework);
  await mkdir(outDir, { recursive: true });

  const flows = await listFlows(flowsDir);
  const selected = flows.filter((f) => {
    if (args.flow && f.id !== args.flow) return false;
    return true;
  });

  if (selected.length === 0 && !args.all && !args.flow) {
    return { ok: true, framework, skeletons: [], written: [] };
  }

  const renderer = RENDERERS[framework];
  const skeletons = [];
  const written = [];
  for (const flow of selected) {
    const slug = slugify(flow.id.replace(/^FLOW-/, ''));
    const ext = fileExt(framework);
    const fname = `${slug}${ext}`;
    const fpath = path.join(outDir, fname);
    const body = renderer(flow);
    await atomicWrite(fpath, body);
    written.push(fpath);

    const relTest = path.relative(cwd, fpath);
    const meta = makeMeta(flow, framework, relTest);
    const metaPath = path.join(outDir, `${slug}.meta.json`);
    await atomicWrite(metaPath, `${JSON.stringify(meta, null, 2)}\n`);
    written.push(metaPath);

    skeletons.push({
      framework,
      flow: flow.id,
      path: fpath,
      meta_path: metaPath,
      status: 'generated-but-not-validated',
    });
  }

  return { ok: true, framework, skeletons, written };
}

function parseArgs(argv) {
  const out = { cwd: process.cwd(), all: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--cwd') out.cwd = argv[++i];
    else if (a === '--flow') out.flow = argv[++i];
    else if (a === '--issue') out.issue = argv[++i];
    else if (a === '--all') out.all = true;
    else if (a === '--framework') out.framework = argv[++i];
    else if (a === '--playwright') out.framework = 'playwright';
    else if (a === '--cypress') out.framework = 'cypress';
    else if (a === '--api') out.framework = 'api';
    else if (a === '--cli') out.framework = 'cli';
    else if (a === '--contract') out.framework = 'contract';
    else if (a === '--smoke') out.framework = 'smoke';
    else if (a === '--help' || a === '-h') out.help = true;
    else {
      console.error(`generate-automation: unknown argument "${a}"`);
      process.exit(2);
    }
  }
  return out;
}

